"""Markdown views: statements, glossary, rules and the three level views (FR-7, FR-8, FR-11).

Draft items are marked ``_(draft)_`` after their term in every Markdown file (FR-10).
"""

from __future__ import annotations

from domain_model.consistency import kind_index
from domain_model.model import (
    TYPE_PREDICATE,
    CardinalityPattern,
    Concept,
    Condition,
    DerivePattern,
    Domain,
    EqualPattern,
    ImpliesPattern,
    Item,
    Ontology,
    Pattern,
    Property,
    Relation,
    Rule,
    SparqlPattern,
    Tree,
    TreeNode,
    ValuesPattern,
)
from domain_model.text.mermaid import is_a_diagram, ontology_diagram, tree_diagram

HEADER = "<!-- Generated by domain-model from the YAML sources of this folder. Do not edit. -->"


def cell(text: object) -> str:
    """Text that is safe inside a Markdown table cell."""
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def draft(entry: Item | Rule) -> str:
    return " _(draft)_" if entry.status == "draft" else ""


def term(entry: Item) -> str:
    """The display term of an item, marked when it is a draft."""
    return entry.label + draft(entry)


def table(head: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    return lines + ["| " + " | ".join(row) + " |" for row in rows]


def glossary_rows(onto: Ontology, max_level: int = 3) -> list[str]:
    """The glossary table: one row per concept, individual, relation and property up to ``max_level``."""
    kinds = kind_index(onto)
    items = sorted((i for i in onto.items if i.level <= max_level), key=lambda i: (i.label.casefold(), i.id))
    head = ["Term", "Id", "Kind", "Synonyms", "Definition", "Level", "Status", "Sources"]
    rows = [
        [
            cell(term(i)),
            f"`{i.id}`",
            kinds[i.id],
            cell(", ".join(i.synonyms)),
            cell(i.definition),
            str(i.level),
            i.status,
            ", ".join(i.source),
        ]
        for i in items
    ]
    return table(head, rows) if rows else ["_No terms yet._"]


def glossary_md(domain: Domain) -> str:
    onto = domain.ontology
    lines = [HEADER, "", f"# {onto.label}: glossary", ""]
    lines += ["Every concept, individual, relation and property, sorted by term.", ""]
    lines += glossary_rows(onto)
    return "\n".join(lines) + "\n"


def statements_md(domain: Domain) -> str:
    lines = [HEADER, "", f"# {domain.ontology.label}: statements", ""]
    lines += [
        "The domain expert's statements, verbatim, in the order given. Items cite them as `source`.",
        "",
    ]
    rows = [[s.id, s.date.isoformat(), str(s.level), cell(s.text)] for s in domain.statements]
    lines += table(["Id", "Date", "Level", "Statement"], rows) if rows else ["_No statements yet._"]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------- rules
def _list(ids: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in ids)


def _condition(c: Condition) -> str:
    if c.has_value is not None:
        value = f"`{c.has_value}`" if isinstance(c.has_value, str) else f"`{c.has_value!r}`"
        return f"has {value} as `{c.path}`"
    if c.in_ is not None:
        return f"has a `{c.path}` value in {_list(c.in_)}"
    if c.class_ is not None:
        return f"has a `{c.path}` value of class `{c.class_}`"
    return f"has at least {c.min} `{c.path}` value(s)"


def _cardinality(p: CardinalityPattern) -> str:
    bounds = [
        f"at least {p.min}" if p.min is not None else "",
        f"at most {p.max}" if p.max is not None else "",
    ]
    of_class = f" of class `{p.class_}`" if p.class_ else ""
    return f"each `{p.focus}` has {' and '.join(bounds)} `{p.path}` value(s){of_class}"


def _values(p: ValuesPattern) -> str:
    if p.in_ is not None:
        allowed = f"one of {_list(p.in_)}"
    elif p.class_ is not None:
        allowed = f"of class `{p.class_}`"
    else:
        allowed = f"of datatype `xsd:{p.datatype}`"
    return f"every `{p.path}` value of a `{p.focus}` is {allowed}"


def _derive(p: DerivePattern) -> str:
    condition = f" that {_condition(p.if_)}" if p.if_ else ""
    if p.add.predicate == TYPE_PREDICATE:
        return f"each `{p.focus}`{condition} is also a `{p.add.object}`"
    return f"each `{p.focus}`{condition} gets `{p.add.predicate}` → `{p.add.object}`"


def pattern_summary(p: Pattern) -> str:
    """One readable line that says what a rule pattern checks or derives."""
    match p:
        case CardinalityPattern():
            return _cardinality(p)
        case ValuesPattern():
            return _values(p)
        case ImpliesPattern():
            return f"if a `{p.focus}` {_condition(p.if_)}, then it {_condition(p.then)}"
        case EqualPattern():
            return f"for each `{p.focus}`, `{p.left}` and `{p.right}` have the same values"
        case DerivePattern():
            return _derive(p)
        case SparqlPattern():
            kind = (
                "SELECT (each result is a violation)"
                if p.select is not None
                else "CONSTRUCT (derived triples)"
            )
            return f"SPARQL {kind} on each `{p.focus}`"


def rule_sections(onto: Ontology, max_level: int = 3) -> list[str]:
    lines: list[str] = []
    for rule in (r for r in onto.rules if r.level <= max_level):
        lines += [f"### {rule.id} · {cell(rule.statement)}{draft(rule)}", ""]
        meta = [
            f"**Kind:** {rule.kind}",
            f"**Pattern:** `{rule.pattern_key}`",
            f"**Level:** {rule.level}",
            f"**Status:** {rule.status}",
            f"**Sources:** {', '.join(rule.source)}",
        ]
        lines += [f"- {' · '.join(meta)}", f"- {pattern_summary(rule.pattern)}"]
        if rule.sparql is not None:
            lines += ["", "```sparql", rule.sparql.query.rstrip(), "```"]
        lines.append("")
    return lines or ["_No rules yet._", ""]


def rules_md(domain: Domain) -> str:
    lines = [HEADER, "", f"# {domain.ontology.label}: rules", ""]
    lines += [
        "Each rule is checked or applied by its shape `<prefix>:<RuleId>_shape` in `rules.shacl.ttl`.",
        "",
    ]
    return "\n".join(lines + rule_sections(domain.ontology)).rstrip() + "\n"


# ---------------------------------------------------------------------------- level views
def _is_a_list(concepts: list[Concept], parent: str | None, depth: int, trail: tuple[str, ...]) -> list[str]:
    """Nested list of the is-a tree; a concept with several parents appears under each parent."""
    lines: list[str] = []
    for c in concepts:
        is_child = parent in c.parents if parent else not c.parents
        if is_child and c.id not in trail:
            lines.append(f"{'  ' * depth}- {cell(term(c))} (`{c.id}`)")
            lines += _is_a_list(concepts, c.id, depth + 1, (*trail, c.id))
    return lines


def _tree_list(nodes: list[TreeNode], concepts: dict[str, Concept], depth: int) -> list[str]:
    lines: list[str] = []
    for node in nodes:
        if node.id in concepts:
            lines.append(f"{'  ' * depth}- {cell(term(concepts[node.id]))} (`{node.id}`)")
            lines += _tree_list(node.children, concepts, depth + 1)
    return lines


def _code(value: str | None) -> str:
    return f"`{value}`" if value else ""


def _up_to[T: (Item | Rule)](entries: list[T], n: int) -> list[T]:
    return [e for e in entries if e.level <= n]


def _relation_row(r: Relation) -> list[str]:
    links = [_code(r.domain), _code(r.range), r.cardinality or "", _code(r.inverse), _code(r.parent)]
    return [cell(term(r)), f"`{r.id}`", *links, ", ".join(r.characteristics), str(r.level)]


def _relations(onto: Ontology, n: int) -> list[str]:
    head = ["Relation", "Id", "Domain", "Range", "Cardinality", "Inverse", "Super-relation"]
    rows = [_relation_row(r) for r in _up_to(onto.relations, n)]
    return table([*head, "Characteristics", "Level"], rows) if rows else ["_None yet._"]


def _property_row(p: Property) -> list[str]:
    datatype = f"`xsd:{p.datatype}`"
    return [cell(term(p)), f"`{p.id}`", _code(p.domain), datatype, p.cardinality or "", str(p.level)]


def _properties(onto: Ontology, n: int) -> list[str]:
    rows = [_property_row(p) for p in _up_to(onto.properties, n)]
    head = ["Property", "Id", "Domain", "Datatype", "Cardinality", "Level"]
    return table(head, rows) if rows else ["_None yet._"]


def _intro(onto: Ontology, n: int) -> list[str]:
    info = onto.level_info(n)
    counts = [
        f"{len(_up_to(onto.concepts, n))} concepts",
        f"{len(_up_to(onto.individuals, n))} individuals",
        f"{len(_up_to(onto.relations, n))} relations",
        f"{len(_up_to(onto.properties, n))} properties",
        f"{len(_up_to(onto.rules, n))} rules",
    ]
    scope = "the whole domain" if n == 3 else f"every item of levels 1–{n}" if n > 1 else "the level-1 items"
    return [
        f"# {onto.label} · level {n}: {info.name}",
        "",
        f"For **{info.audience}**. Levels are cumulative: this view holds {scope}.",
        "",
        f"Contents: {', '.join(counts)}. Items marked _(draft)_ are proposed wording, not yet confirmed.",
    ]


def _trees(trees: list[Tree], onto: Ontology, n: int) -> list[str]:
    concepts = {c.id: c for c in _up_to(onto.concepts, n)}
    lines: list[str] = []
    for tree in trees:
        lines += [
            "",
            f"## {tree.label}",
            "",
            *(_tree_list(tree.top, concepts, 0) or ["_None at this level._"]),
        ]
    return lines


def _diagrams(domain: Domain, n: int) -> list[str]:
    onto = domain.ontology
    lines = ["", "## Diagrams", "", "### Taxonomy (is-a)", "", *is_a_diagram(onto, n)]
    for tree in domain.taxonomy.trees:
        lines += ["", f"### {tree.label}", "", *tree_diagram(onto, tree, n)]
    return lines + ["", "### Ontology graph", "", *ontology_diagram(onto, n)]


def level_md(domain: Domain, n: int) -> str:
    """The cumulative view of level ``n``: every section, filtered to items with level ≤ n (FR-8).

    The diagrams come first, right after the intro: they are understood faster than the text sections.
    """
    onto = domain.ontology
    concepts = _up_to(onto.concepts, n)
    lines = [HEADER, "", *_intro(onto, n), *_diagrams(domain, n)]
    lines += ["", "## Glossary", "", *glossary_rows(onto, n)]
    lines += ["", "## Taxonomy (is-a)", "", *(_is_a_list(concepts, None, 0, ()) or ["_No concepts yet._"])]
    lines += _trees(domain.taxonomy.trees, onto, n)
    lines += [
        "",
        "## Relations",
        "",
        *(_relations(onto, n) if _up_to(onto.relations, n) else ["_None yet._"]),
    ]
    lines += [
        "",
        "## Properties",
        "",
        *(_properties(onto, n) if _up_to(onto.properties, n) else ["_None yet._"]),
    ]
    lines += ["", "## Rules", "", *rule_sections(onto, n)]
    return "\n".join(lines) + "\n"
