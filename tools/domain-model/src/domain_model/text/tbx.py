"""The glossary as TBX (ISO 30042:2019, TBX-Basic dialect, DCA style; FR-7, FR-9, FR-10).

One ``conceptEntry`` per concept, individual, relation and property. Kind, level, status and sources
are ``note`` elements; the preferred term is the label, synonyms are admitted terms. The XML is written
by a small string builder (every text and attribute value escaped), so output order is fixed.
"""

from __future__ import annotations

from html import escape

from domain_model.consistency import kind_index
from domain_model.model import Domain, Item

TBX_NS = "urn:iso:std:iso:30042:ed-2"
HEADER = "Generated by domain-model from ontology.yaml. Do not edit."


def _element(indent: int, tag: str, text: str, **attrib: str) -> str:
    attributes = "".join(f' {k}="{escape(v)}"' for k, v in attrib.items())
    return f"{'  ' * indent}<{tag}{attributes}>{escape(text, quote=False)}</{tag}>"


def _term_sec(text: str, status: str) -> list[str]:
    return [
        "        <termSec>",
        _element(5, "term", text),
        _element(5, "termNote", status, type="administrativeStatus"),
        "        </termSec>",
    ]


def _entry(item: Item, kind: str, lang: str) -> list[str]:
    notes = [
        f"kind: {kind}",
        f"level: {item.level}",
        f"status: {item.status}",
        f"source: {', '.join(item.source)}",
    ]
    lines = [f'    <conceptEntry id="{escape(item.id)}">', *(_element(3, "note", n) for n in notes)]
    lines.append(f'      <langSec xml:lang="{escape(lang)}">')
    if item.definition:
        lines.append(_element(4, "descrip", item.definition, type="definition"))
    lines += _term_sec(item.label, "preferredTerm-admn-sts")
    for synonym in item.synonyms:
        lines += _term_sec(synonym, "admittedTerm-admn-sts")
    return [*lines, "      </langSec>", "    </conceptEntry>"]


def glossary_tbx(domain: Domain) -> bytes:
    onto = domain.ontology
    kinds = kind_index(onto)
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f"<!-- {HEADER} -->",
        f'<tbx xmlns="{TBX_NS}" type="TBX-Basic" style="dca" xml:lang="{escape(onto.language)}">',
        "  <tbxHeader>",
        "    <fileDesc>",
        "      <titleStmt>",
        _element(4, "title", f"{onto.label}: glossary"),
        "      </titleStmt>",
        "      <sourceDesc>",
        _element(4, "p", f"Generated from ontology.yaml (namespace {onto.namespace})."),
        "      </sourceDesc>",
        "    </fileDesc>",
        "  </tbxHeader>",
        "  <text>",
        "    <body>",
    ]
    for item in onto.items:
        lines += [f"  {line}" for line in _entry(item, kinds[item.id], onto.language)]
    lines += ["    </body>", "  </text>", "</tbx>"]
    return ("\n".join(lines) + "\n").encode()
