"""Mermaid diagrams: the is-a tree, each extra tree, and the ontology graph (FR-3, FR-8).

Node ids are item ids (``[A-Za-z0-9_]``); labels are always quoted, with ``#`` and ``"`` written as
Mermaid entity codes, so labels such as ``audio/visual "AV" item`` render.
"""

from __future__ import annotations

from domain_model.model import Concept, Domain, Ontology, Tree, TreeNode

HEADER = "<!-- Generated by domain-model from the YAML sources of this folder. Do not edit. -->"


def label(text: str) -> str:
    """A quoted Mermaid label."""
    return '"' + text.replace("#", "#35;").replace('"', "#quot;") + '"'


def _node(c: Concept) -> str:
    suffix = " (draft)" if c.status == "draft" else ""
    return f"    {c.id}[{label(c.label + suffix)}]"


def _block(kind: str, body: list[str], empty: str) -> list[str]:
    return ["```mermaid", kind, *(body or [f"    empty[{label(empty)}]"]), "```"]


def _concepts(onto: Ontology, max_level: int) -> list[Concept]:
    return [c for c in onto.concepts if c.level <= max_level]


def is_a_diagram(onto: Ontology, max_level: int = 3) -> list[str]:
    """``flowchart BT``: child --> parent; a concept with several parents is one node with several edges."""
    concepts = _concepts(onto, max_level)
    body = [_node(c) for c in concepts]
    body += [f"    {c.id} --> {p}" for c in concepts for p in c.parents]
    return _block("flowchart BT", body, "no concepts yet")


def _tree_edges(nodes: list[TreeNode], relation: str, parent: str | None, keep: set[str]) -> list[str]:
    edges: list[str] = []
    for node in nodes:
        if node.id not in keep:
            continue
        if parent is not None:
            edges.append(f"    {node.id} -->|{label(relation)}| {parent}")
        edges += _tree_edges(node.children, relation, node.id, keep)
    return edges


def _tree_ids(nodes: list[TreeNode], keep: set[str]) -> list[str]:
    ids: list[str] = []
    for node in nodes:
        if node.id in keep:
            ids += [node.id, *_tree_ids(node.children, keep)]
    return ids


def tree_diagram(onto: Ontology, tree: Tree, max_level: int = 3) -> list[str]:
    """An extra tree from taxonomy.yaml (``flowchart BT``: child --relation--> parent)."""
    concepts = {c.id: c for c in _concepts(onto, max_level)}
    ids = list(dict.fromkeys(_tree_ids(tree.top, set(concepts))))
    body = [_node(concepts[i]) for i in ids]
    body += _tree_edges(tree.top, tree.relation, None, set(concepts))
    return _block("flowchart BT", body, "no concepts at this level")


def ontology_diagram(onto: Ontology, max_level: int = 3) -> list[str]:
    """``flowchart LR``: classes as nodes, relations as labelled edges, is-a as dotted edges."""
    concepts = _concepts(onto, max_level)
    shown = {c.id for c in concepts}
    body = [_node(c) for c in concepts]
    for r in onto.relations:
        if r.level <= max_level and r.domain in shown and r.range in shown:
            draft = " (draft)" if r.status == "draft" else ""
            body.append(f"    {r.domain} -->|{label(r.label + draft)}| {r.range}")
    body += [f"    {c.id} -.->|{label('is a')}| {p}" for c in concepts for p in c.parents]
    return _block("flowchart LR", body, "no concepts yet")


def diagrams_md(domain: Domain) -> str:
    onto = domain.ontology
    lines = [HEADER, "", f"# {onto.label}: diagrams", "", "The whole domain (all levels).", ""]
    lines += ["## Taxonomy (is-a)", "", *is_a_diagram(onto), ""]
    for tree in domain.taxonomy.trees:
        lines += [f"## {tree.label}", "", *tree_diagram(onto, tree), ""]
    lines += ["## Ontology graph", "", *ontology_diagram(onto)]
    return "\n".join(lines) + "\n"
