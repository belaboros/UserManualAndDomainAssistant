"""AC-3 (RDF part), AC-6: deterministic Turtle, RDF/XML and JSON-LD of one graph (plan 0002, T7)."""

from __future__ import annotations

import os
import subprocess
import sys

import pytest
from dm_fixtures import EXAMPLE_DIR
from domain_model.load import load_domain
from domain_model.model import Domain
from domain_model.rdf.owl import owl_graph
from domain_model.rdf.serialize import FORMATS, serialize
from rdflib import Graph
from rdflib.compare import isomorphic

HEADER = "Generated by domain-model from ontology.yaml. Do not edit."


def _owl() -> Graph:
    domain, _ = load_domain(EXAMPLE_DIR)
    assert isinstance(domain, Domain)
    return owl_graph(domain)


def test_rdfxml_and_jsonld_isomorphic_to_turtle() -> None:
    graph = _owl()
    parsed = {fmt: Graph().parse(data=serialize(graph, fmt, HEADER), format=fmt) for fmt in FORMATS}
    assert isomorphic(parsed["turtle"], graph)
    assert isomorphic(parsed["xml"], parsed["turtle"])
    assert isomorphic(parsed["json-ld"], parsed["turtle"])


def test_list_valued_axiom_survives_rdfxml() -> None:
    graph = _owl()
    xml = Graph().parse(data=serialize(graph, "xml", HEADER), format="xml")
    query = (
        "PREFIX owl: <http://www.w3.org/2002/07/owl#> PREFIX rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#>"
        " ASK { ?c owl:unionOf ?l . ?l rdf:rest/rdf:rest rdf:nil }"
    )
    assert xml.query(query).askAnswer
    assert len(xml) == len(graph)


@pytest.mark.parametrize(("fmt", "marker"), [("turtle", "# "), ("xml", "<!-- ")])
def test_header_comment(fmt: str, marker: str) -> None:
    text = serialize(_owl(), fmt, HEADER).decode()
    assert f"{marker}{HEADER}" in text.splitlines()[0:3][-1] or f"{marker}{HEADER}" in text[:300]


@pytest.mark.parametrize("fmt", FORMATS)
def test_serialisation_is_byte_identical_in_process(fmt: str) -> None:
    assert serialize(_owl(), fmt, HEADER) == serialize(_owl(), fmt, HEADER)


SCRIPT = """
import sys
from pathlib import Path
from domain_model.load import load_domain
from domain_model.rdf.owl import owl_graph
from domain_model.rdf.serialize import FORMATS, serialize
domain, _ = load_domain(Path(sys.argv[1]))
g = owl_graph(domain)
sys.stdout.buffer.write(b"".join(serialize(g, f, "h") for f in FORMATS))
"""


def test_serialisation_is_byte_identical_across_processes() -> None:
    outputs = []
    for seed in ("1", "2"):
        env = {**os.environ, "PYTHONHASHSEED": seed}
        result = subprocess.run(  # noqa: S603 - fixed interpreter and script
            [sys.executable, "-c", SCRIPT, str(EXAMPLE_DIR)], capture_output=True, env=env, check=True
        )
        outputs.append(result.stdout)
    assert outputs[0] == outputs[1]


@pytest.mark.parametrize("fmt", FORMATS)
def test_empty_graph_serialises(fmt: str) -> None:
    assert Graph().parse(data=serialize(Graph(), fmt, HEADER), format=fmt) is not None
